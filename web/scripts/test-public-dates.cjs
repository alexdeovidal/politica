const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
const Database=require('better-sqlite3');
const compiled=ts.transpileModule(fs.readFileSync(path.join(__dirname,'../src/lib/normalize.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const sourceModule={exports:{}};
new Function('module','exports',compiled)(sourceModule,sourceModule.exports);
const normalize=sourceModule.exports.normalizePublicTimestamp;
assert.equal(normalize('Wed Sep 30 04:14:59 +0000 2020'),'2020-09-30T04:14:59.000Z');
assert.equal(normalize('2021-09-29T23:05:24Z'),'2021-09-29T23:05:24.000Z');
assert.equal(normalize('1601439299'),normalize('1601439299000'));
assert.equal(normalize('invalid'),null);
assert.equal(normalize(null),null);
const db=new Database(':memory:');db.function('public_timestamp',{deterministic:true},normalize);
db.exec('CREATE TABLE posts(date TEXT)');
for(const date of ['Wed Sep 30 04:14:59 +0000 2020','2021-09-29T23:05:24Z'])db.prepare('INSERT INTO posts VALUES(?)').run(date);
assert.equal(db.prepare('SELECT public_timestamp(date) AS date FROM posts ORDER BY public_timestamp(date) DESC LIMIT 1').get().date,'2021-09-29T23:05:24.000Z');
assert.equal(db.prepare("SELECT count(*) AS n FROM posts WHERE substr(public_timestamp(date),1,10)>='2021-01-01'").get().n,1);
db.close();console.log('Public dates: mixed formats, chronological order and period filters passed');
